"""Shared repo-root-relative path helpers.

Every script under scripts/ resolves paths relative to the repository root
the same way; this centralizes that instead of re-deriving it per script.

METADATA_DIR (local, git-tracked) holds only small reference/code-structure
tables that define what a code *means*: SNI digit/section mappings and
cross-version crosswalks. Everything that is generated by the pipeline, or
cached from an external source, is "data" in the project sense and lives on
LUNARC nobackup storage instead — see LUNARC_DATA_ROOT below. Rule of thumb:
if a script writes it, or downloads/caches a multi-MB external source file,
it's data, not metadata.
"""

import os
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[3]
METADATA_DIR = PROJECT_ROOT / "metadata"
RESULTS_DIR = PROJECT_ROOT / "results"
CONFIG_PATH = PROJECT_ROOT / "config.yaml"

# LUNARC nobackup project storage — not portable off this HPC allocation,
# consistent with the other hardcoded /lunarc/... paths already used for
# individual-level SCB microdata (see build_labor_relatedness.py's
# DATA_ROOT). Named LUNARC_* here specifically to avoid colliding with that
# other, differently-scoped DATA_ROOT.
#
# LATENT_DATA_ROOT env var overrides the default root so ablation/test runs
# (e.g. under .../DataLatentIndustryRepresentations/ablations) can write
# processed/embedding output to a separate tree without touching production
# artifacts under the same --name. Unset by default -> unchanged behavior.
LUNARC_DATA_ROOT = Path(os.environ.get(
    "LATENT_DATA_ROOT",
    "/lunarc/nobackup/projects/lu2025-17-39/DataLatentIndustryRepresentations",
))
RAW_DATA_DIR = LUNARC_DATA_ROOT / "raw"          # cached/downloaded external source files
PROCESSED_DATA_DIR = LUNARC_DATA_ROOT / "processed"  # pipeline-generated artifacts
EMBEDDING_DIR = LUNARC_DATA_ROOT / "embedding"   # trained sentence-transformer checkpoints + output embeddings

# Multi-MB generated outputs that don't belong in the git-tracked results/
# tree (same rule of thumb as the module docstring) — currently just the
# plotly interactive HTML maps, several MB each per run.
INTERACTIVE_PLOTS_DIR = LUNARC_DATA_ROOT / "results" / "interactive_plots"
